import { createElement, type ComponentType } from 'react';

/**
 * Mapa "ferramenta -> tela da ferramenta" (as mesmas telas das paginas de
 * ferramentas, so que carregadas sob demanda dentro do leitor).
 * Gerado a partir de src/app/[locale]/tools/[tool]/page.tsx.
 */
export type ToolLoader = () => Promise<ComponentType>;

function bind<P extends object>(Component: ComponentType<P>, props: P): ComponentType {
  const Bound = () => createElement(Component, props);
  Bound.displayName = 'Bound';
  return Bound;
}

